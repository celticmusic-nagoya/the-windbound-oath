"""HairHarpy v2.0.0 native (.hairmesh JSON, app 'anime-hair-modeler' v1) authoring + bounded app runner.

Verified facts (2026-11-23, tag v2.0.0 source + runtime):
- a project saved from a --shot session has no "app" key unless the script starts with `newproj` (else reopen fails
  with "Not a HairHarpy project");
- a lock = >=2 curves (root -> tip) sharing one tip anchor id; `select <curves,wall>; cocoon` accepts it and `convert`
  builds the lock mesh (qualified with 2 strands -> 111 v / 55 f);
- `cutc <curve> <seg> <u> ... <split|up|down>` is the Scissors curve cut (no viewport needed).
Only the continuation group is edited; crown, lower connector and the head mesh are the protected scope.
"""
import hashlib
import json
import math
import os
import subprocess
import time
from pathlib import Path

APP = os.environ.get("HAIRHARPY_APP", "/tmp/hh-bin/app/HairHarpy-2.0.0/AppRun")


def sha_bytes(b):
    return hashlib.sha256(b).hexdigest()


def sha(p):
    return sha_bytes(Path(p).read_bytes())


def load(p):
    d = json.loads(Path(p).read_text(encoding="utf-8"))
    if d.get("app") != "anime-hair-modeler":
        raise ValueError("not a reopenable HairHarpy project (missing app key)")
    return d


def index(d):
    return {i["id"]: i for i in d["items"]}, {a["id"]: a for a in d["anchors"]}


def protected_fingerprint(d):
    """Crown, its curves/connector, the head mesh and every anchor they use (canonical JSON)."""
    items, anchors = index(d)
    keep = [i for i in d["items"] if i["type"] in ("crown", "imesh")
            or (i["type"] == "curve" and items.get(i.get("parent"), {}).get("type") == "group"
                and items[i["parent"]]["name"].startswith("Crown") and "continuation" not in items[i["parent"]]["name"])]
    used = sorted({a for i in keep for a in i.get("anchors", [])})
    rec = {"items": sorted((json.dumps(i, sort_keys=True) for i in keep)),
           "anchors": [json.dumps(anchors[a], sort_keys=True) for a in used if a in anchors]}
    return sha_bytes(json.dumps(rec, sort_keys=True).encode())


def connector_roots(d):
    items, anchors = index(d)
    low = next(i for i in d["items"] if i["type"] == "curve" and i["name"] == "Lower connector")
    return [(a, anchors[a]["p"]) for a in low["anchors"]]


def ellipsoid_out(p, ax, margin):
    """Push a point radially (in the horizontal plane) to `margin` outside the head ellipsoid at its height."""
    x, y, z = p
    a, b, c = ax
    k = max(0.0, 1 - (y / b) ** 2)
    if k <= 0:
        return [x, y, z]
    ex, ez = a * math.sqrt(k), c * math.sqrt(k)
    ang = math.atan2(z / ez, x / ex) if (x or z) else 0.0
    return [(ex + margin) * math.cos(ang), y, (ez + margin) * math.sin(ang)]


def author_locks(d, bp, controls):
    """Replace the continuation's curves/walls with blueprint locks. controls[lock_id] = {"tip_y": .., "bend": ..}."""
    items, anchors = index(d)
    cont = next(i for i in d["items"] if i["type"] == "group" and "continuation" in i["name"])
    # rebuild: generated cocoons and converted meshes are regenerated by HairHarpy from the authored locks
    gen = {i["id"] for i in d["items"] if i["type"] in ("cocoon", "mesh")}
    for i in d["items"]:
        if "children" in i:
            i["children"] = [c for c in i["children"] if c not in gen]
    d["roots"] = [r for r in d.get("roots", []) if r not in gen]
    d["items"] = [i for i in d["items"] if i["id"] not in gen]
    items, anchors = index(d)
    drop = set(cont["children"])
    for gid in [i["id"] for i in d["items"] if i.get("parent") == cont["id"] and i["type"] == "group"]:
        drop |= set(items[gid].get("children", [])) | {gid}
    used_elsewhere = {a for i in d["items"] if i["id"] not in drop for a in i.get("anchors", [])}
    dropped_anchors = {a for i in d["items"] if i["id"] in drop for a in i.get("anchors", [])} - used_elsewhere
    d["items"] = [i for i in d["items"] if i["id"] not in drop]
    d["anchors"] = [a for a in d["anchors"] if a["id"] not in dropped_anchors]
    items, anchors = index(d)
    nid = [max(max(items), max(anchors)) + 1]

    def new_id():
        nid[0] += 1
        return nid[0] - 1

    def anchor(p):
        k = new_id()
        d["anchors"].append({"id": k, "p": [float(v) for v in p], "s": 1})
        return k

    roots = connector_roots(d)
    ax, clr = bp["head"]["semi_axes_xyz"], bp["strand"]["clearance"]
    children, made = [], {}
    for lk in bp["locks"]:
        ctl = controls[lk["id"]]
        gid = new_id()
        strands = []
        tips = []
        rc = [(roots[lk["roots"][0]][1][i] + roots[lk["roots"][1]][1][i]) / 2 for i in range(3)]
        inset = bp["strand"].get("root_inset", 0.0)  # strands pulled toward the lock centre: neighbours do not share paths
        for r in lk["roots"]:
            aid, rp0 = roots[r]
            rp = [rp0[i] + (rc[i] - rp0[i]) * inset for i in range(3)]
            p1 = ellipsoid_out([rp[0], rp0[1] - 0.025, rp[2]], ax, clr)
            p2 = ellipsoid_out([rp[0], bp["strand"]["equator_y"], rp[2]], ax, clr + 0.004)
            # below the equator hair hangs straight under gravity: horizontal position continuous in tip height
            # (the head is narrower there, so clearance holds); tip_out widens the lock end slightly
            hr = math.hypot(p2[0], p2[2]) or 1e-9
            tips.append([p2[0] * (1 + lk["tip_out"] / hr), ctl["tip_y"], p2[2] * (1 + lk["tip_out"] / hr)])
            strands.append((aid, p1, p2))
        tip = [(tips[0][0] + tips[1][0]) / 2, ctl["tip_y"], (tips[0][2] + tips[1][2]) / 2]
        tip_id = anchor(tip)
        curve_ids = []
        for n, (aid, p1, p2) in enumerate(strands):
            mid_y = (p2[1] + ctl["tip_y"]) / 2
            # bend: the lower half bows outward/back by `bend`
            hr = math.hypot(p2[0], p2[2]) or 1e-9
            f = 1 + ctl["bend"] / hr  # bend: the lower half bows outward by `bend`
            p3 = [p2[0] * f, mid_y, p2[2] * f]
            cid = new_id()
            d["items"].append({"anchors": [aid, anchor(p1), anchor(p2), anchor(p3), tip_id], "fair": 0.5, "id": cid,
                               "name": f"{lk['id']}_s{n}", "ovr": [], "parent": gid, "round": 0.6, "seg": True,
                               "type": "curve", "visible": True})
            curve_ids.append(cid)
        wid = new_id()
        d["items"].append({"a": curve_ids[0], "b": curve_ids[1], "id": wid, "name": f"{lk['id']}_wall",
                           "p": {"bulge": 0.15, "flip": False, "segs": 1}, "parent": gid, "type": "surface", "visible": True})
        g = {k: v for k, v in cont.items() if k not in ("children", "id", "name", "parent", "gpivot", "cont")}
        g.update({"children": curve_ids + [wid], "id": gid, "name": lk["id"], "parent": cont["id"], "cont": False,
                  "gpivot": tip, "expanded": False})
        d["items"].append(g)
        children.append(gid)
        made[lk["id"]] = {"group": gid, "curves": curve_ids, "wall": wid, "tip_anchor": tip_id}
    cont["children"] = children
    return made


def run_app(native, events, workdir, deadline, display, shot_name="shot.png", timeout_cap=240):
    """Run HairHarpy on a native project with a command script; bounded by the session deadline."""
    remaining = deadline - time.monotonic()
    if remaining <= 5:
        raise TimeoutError("insufficient budget for HairHarpy operation")
    workdir = Path(workdir)
    workdir.mkdir(parents=True, exist_ok=True)
    shot = workdir / shot_name
    env = dict(os.environ, DISPLAY=display, VK_ICD_FILENAMES="/usr/share/vulkan/icd.d/lvp_icd.json",
               QT_QPA_PLATFORM="xcb", HOME=str(workdir / "home"))
    (workdir / "home").mkdir(exist_ok=True)
    args = [APP] + ([str(native)] if native else []) + ["--shot", str(shot), "--size", "1500x810", "--events", events]
    p = subprocess.run(args, env=env, capture_output=True, text=True, timeout=min(timeout_cap, remaining - 2))
    log = (Path(str(shot) + ".txt").read_text(encoding="utf-8") if Path(str(shot) + ".txt").exists() else "")
    if p.returncode != 0 or not log:
        raise RuntimeError(f"HairHarpy run failed rc={p.returncode}: {p.stderr[-400:]}")
    return log, shot


def lock_controls(d):
    """Current controls read back from the native file: tip height of each lock (shared tip anchor)."""
    items, anchors = index(d)
    out = {}
    for g in d["items"]:
        if g["type"] == "group" and g["name"][:1] == "L" and g["name"][1:].isdigit():
            curves = [items[c] for c in g["children"] if items.get(c, {}).get("type") == "curve"]
            tips = {c["anchors"][-1] for c in curves}
            if len(tips) == 1:
                out[g["name"]] = {"tip_y": anchors[tips.pop()]["p"][1]}
    return out


def cocoon_convert_events(d, extra):
    items, _ = index(d)
    ev = ["room hair", "wait 300"]
    for g in sorted((i for i in d["items"] if i["type"] == "group" and i["name"][:1] == "L" and i["name"][1:].isdigit()),
                    key=lambda i: i["name"]):
        ev += ["select " + ",".join(str(c) for c in g["children"]), "cocoon", "wait 150"]
    ev += ["selcocoons", "convert", "wait 1500", "convsum", "meshdump"] + extra
    return ";".join(ev)
