const assert=require("node:assert/strict");
const policy=require("./map_graphics_policy.js");
const bridge=require("./map_canvas_quality.js");
const calls=[];
const ctx={setTransform:(...args)=>calls.push(args)};
const canvas={width:0,height:0,style:{},getContext:()=>ctx};
let c=bridge.configure(canvas,390,844,2,policy.resolve("low"),policy);
assert.deepEqual([c.width,c.height],[390,844]);
assert.deepEqual(calls.pop(),[1,0,0,1,0,0]);
c=bridge.configure(canvas,390,844,2,policy.resolve("ultra"),policy);
assert.deepEqual([c.width,c.height],[780,1688]);
assert.equal(canvas.style.width,"390px");
assert.deepEqual(calls.pop(),[2,0,0,2,0,0]);
const low=policy.resolve("low");
assert.equal(bridge.shouldRender({id:"door",interactive:true,category:"decorative_vegetation"},low,policy),true);
assert.equal(bridge.shouldRender({id:"event",eventCritical:true,category:"decorative_vegetation"},low,policy),true);
assert.equal(bridge.shouldRender({id:"wall",category:"architecture"},low,policy),true);
assert.equal(bridge.shouldRender({id:"grass",category:"decorative_vegetation"},low,policy),bridge.shouldRender({id:"grass",category:"decorative_vegetation"},low,policy));
assert.throws(()=>bridge.configure(null,100,100,1,low,policy));
console.log("MAP-GFX-03 PASS");
