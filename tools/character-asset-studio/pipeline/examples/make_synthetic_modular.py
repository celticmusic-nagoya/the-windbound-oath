#!/usr/bin/env python3
"""Generate the synthetic 4-layer example used to exercise the layer pipeline (no real character art).

    python3 tools/character-asset-studio/pipeline/examples/make_synthetic_modular.py [--overwrite]

Writes examples/synthetic_modular/parts/<view>/fNN/<layer>_<part>.png and modular_character.json
(cas/modular-character/0.7). Shapes are plain rectangles/ellipses so nothing here resembles any design.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from caslib import core  # noqa: E402
from PIL import Image, ImageDraw  # noqa: E402

OUT = Path(__file__).resolve().parent / "synthetic_modular"
CANVAS = {"width": 240, "height": 320}
ANCHOR = [120, 308]
FRAMES = 2
# partId, layer, zOrder, colour, draw(d, view, frame)


def body(d, v, f):
    sx = 0 if v in ("front", "back") else -6
    d.ellipse([104 + sx, 40, 136 + sx, 76], fill=(190, 190, 196, 255))                 # head
    d.rectangle([108 + sx, 76, 132 + sx, 180], fill=(190, 190, 196, 255))              # torso
    step = 4 if f else -4
    d.rectangle([106 + sx + step, 180, 118 + sx + step, 308], fill=(190, 190, 196, 255))  # legs (move per frame)
    d.rectangle([122 + sx - step, 180, 134 + sx - step, 308], fill=(190, 190, 196, 255))


def socks(d, v, f):
    step = 4 if f else -4
    d.rectangle([106 + step, 240, 118 + step, 300], fill=(40, 34, 44, 255))
    d.rectangle([122 - step, 240, 134 - step, 300], fill=(40, 34, 44, 255))


def skirt(d, v, f):
    d.polygon([(104, 150), (136, 150), (146, 205), (94, 205)], fill=(110, 50, 150, 255))


def robe_rear(d, v, f):
    d.polygon([(96, 90), (144, 90), (170, 290), (70, 290)], fill=(70, 30, 100, 255))


def hat(d, v, f):
    d.polygon([(120, 4), (100, 44), (140, 44)], fill=(120, 60, 170, 255))
    d.rectangle([84, 40, 156, 48], fill=(120, 60, 170, 255))


PARTS = [("body", "L0_BASE_BODY", 10, body), ("socks", "L1_UNDERWEAR", 110, socks), ("skirt", "L2_BASE_OUTFIT", 210, skirt),
         ("robe_rear", "L3_OUTER_ACCESSORIES", -10, robe_rear), ("hat", "L3_OUTER_ACCESSORIES", 320, hat)]


def main(overwrite=False):
    parts = []
    anchor = {"px": ANCHOR, "n": core.to_norm(ANCHOR, CANVAS)}
    for v in core.VIEWS:
        for f in range(FRAMES):
            for pid, layer, z, fn in PARTS:
                im = Image.new("RGBA", (CANVAS["width"], CANVAS["height"]), (0, 0, 0, 0))
                fn(ImageDraw.Draw(im), v, f)
                p = OUT / "parts" / v / f"f{f:02d}" / f"{layer}_{pid}.png"
                if core.is_protected(core.rel(p)):
                    raise SystemExit(f"protected: {p}")
                if p.exists() and not overwrite:
                    raise SystemExit(f"exists: {p} (use --overwrite; this script only rewrites its own synthetic example)")
                p.parent.mkdir(parents=True, exist_ok=True)
                im.save(p, compress_level=9)
                sha = core.sha256_file(p)
                part = {"schema": "cas/modular-part/0.7", "characterId": "synthetic", "view": v, "frameIndex": f, "canvas": CANVAS,
                        "layerId": layer, "partId": pid, "zOrder": z, "anchorSet": {"anchor": anchor},
                        "sourceAsset": {"path": core.rel(p), "sha256": sha, "width": CANVAS["width"], "height": CANVAS["height"], "mode": "RGBA"},
                        "sha256": sha, "approvalStatus": "UNAPPROVED_CANDIDATE", "measurementStatus": "DESIGNED_CANDIDATE",
                        "sourceEvidence": [{"kind": "synthetic_example", "note": "generated by make_synthetic_modular.py"}]}
                if layer == "L0_BASE_BODY":
                    part["bodyGuidePolicy"] = "adult_nonexplicit_anatomy"
                if pid == "robe_rear":
                    part["occlusion"] = {"occludedBy": ["body", "socks", "skirt"], "note": "rear panel drawn behind the body although it is an L3 part"}
                parts.append(part)
    doc = {"schema": "cas/modular-character/0.7", "characterId": "synthetic", "ageCategory": "adult", "bodyGuidePolicy": "adult_nonexplicit_anatomy",
           "canvas": CANVAS, "anchor": anchor, "views": list(core.VIEWS), "frameCount": FRAMES,
           "layerCatalog": "tools/character-asset-studio/profiles/layer_catalog.json", "parts": parts,
           "note": "Synthetic shapes for pipeline tests and examples only (no character design)."}
    (OUT / "modular_character.json").write_text(core.stable_dumps(doc), encoding="utf-8")
    print(core.rel(OUT / "modular_character.json"), len(parts), "parts")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--overwrite", action="store_true")
    main(ap.parse_args().overwrite)
