"""Layer verification pipeline (TASK E, v0.7): manifest, SHA-256, PNG checks, anchors, ON/OFF compositing,
4-view comparison sheets and per-frame motion consistency for a cas/modular-character/0.7 document.

Composites and sheets are previews written to separate files (listed in layer_outputs.json so they can be
regenerated); source parts are never modified and nothing is adopted.
"""
from pathlib import Path

from .core import REPO_ROOT, VIEWS, guard_write, load_json, rel, sha256_bytes, sha256_file, stable_dumps
from .imageqa import design_protection_checks, measure
from .modular import LAYERS, check_character, compose
from .report import Checks, make_report

OUTPUTS = "layer_outputs.json"


# ---------- output bookkeeping ----------
def record_outputs(out_dir, entries, repo_root=REPO_ROOT):
    """Maintain out_dir/layer_outputs.json (cas/layer-outputs/0.7) listing generated previews."""
    out_dir = Path(out_dir)
    p = out_dir / OUTPUTS
    doc = load_json(p) if p.exists() else {"schema": "cas/layer-outputs/0.7", "status": "UNAPPROVED_REFERENCE",
                                           "note": "Preview images generated by the layer pipeline. Not source assets, not adoptable.", "outputs": []}
    if doc.get("schema") != "cas/layer-outputs/0.7":
        raise ValueError(f"{p} is not a layer-outputs file")
    by = {o["path"]: o for o in doc["outputs"]}
    for e in entries:
        by[e["path"]] = e
    doc["outputs"] = [by[k] for k in sorted(by)]
    guard_write(p, repo_root, overwrite=True) if p.exists() else guard_write(p, repo_root)
    p.write_text(stable_dumps(doc), encoding="utf-8")
    return doc


def _save(img, path, overwrite, repo_root):
    o = guard_write(path, repo_root, overwrite)
    o.parent.mkdir(parents=True, exist_ok=True)
    img.save(o, compress_level=9)
    return {"path": rel(o, repo_root), "sha256": sha256_file(o)}


# ---------- 1. manifest ----------
def layer_manifest(doc, root=None):
    files = []
    for p in sorted(doc["parts"], key=lambda p: (p["view"], p["frameIndex"], p["zOrder"], p["partId"])):
        s = p["sourceAsset"]
        files.append({"path": s["path"], "sha256": s["sha256"], "bytes": 0, "status": p["approvalStatus"],
                      "role": f"{p['layerId']}/{p['partId']}/{p['view']}/f{p['frameIndex']:02d}", "width": s["width"], "height": s["height"], "mode": s["mode"]})
    import os
    common = os.path.commonpath([str(Path(f["path"]).parent) for f in files]) if files else "."
    return {"schema": "cas/manifest/0.5", "root": root or Path(common).as_posix(), "files": files,
            "note": f"Layer manifest for {doc['characterId']} ({len(files)} parts, 4-layer model v0.7). Byte counts filled on build."}


def fill_bytes(m, repo_root=REPO_ROOT):
    for f in m["files"]:
        p = Path(repo_root) / f["path"]
        if p.exists():
            f["bytes"] = p.stat().st_size
    return m


# ---------- 2-7. QA ----------
def layer_qa(doc, doc_path=None, repo_root=REPO_ROOT):
    ck = Checks()
    for r in check_character(doc, repo_root):         # schema, shared anchors, sha fields, files, v2.0 link
        ck.rows.append(r)
    if any(r["id"] == "schema_valid" and r["result"] != "PASS" for r in ck.rows):
        return make_report({"kind": "modular-character"}, ck.rows)
    W, H = doc["canvas"]["width"], doc["canvas"]["height"]
    ay = doc["anchor"]["px"][1]
    meas = {}
    for p in doc["parts"]:
        scope = f"{p['view']}/f{p['frameIndex']:02d}/{p['layerId']}/{p['partId']}"
        f = Path(repo_root) / p["sourceAsset"]["path"]
        if not f.exists():
            continue
        m = measure(f)
        meas[(p["view"], p["partId"], p["frameIndex"])] = (m, sha256_file(f), p)
        ck.add("png_dimensions", scope, "PASS" if (m["width"], m["height"]) == (W, H) else "FAIL", detail=[m["width"], m["height"]])
        ck.add("png_rgba", scope, "PASS" if m["mode"] == "RGBA" else "FAIL", detail=m["mode"])
        if m["mode"] != "RGBA":
            continue
        ck.add("transparent_border", scope, "PASS" if m["borderNonZero"] == 0 else "FAIL", detail={"nonZeroBorderPixels": m["borderNonZero"]})
        ck.add("real_transparency", scope, "PASS" if m["transparentPixels"] > 0 else "FAIL")
        ck.add("content_present", scope, "PASS" if m.get("bbox") else "FAIL")
        if p["layerId"] == "L0_BASE_BODY" and m.get("bbox"):
            dy = m["contact"]["bottomRow"] - ay
            ck.add("anchor_ground_contact", scope, "PASS" if abs(dy) <= max(2, round(H * 0.004)) else "FAIL", detail={"bottomRow": m["contact"]["bottomRow"], "anchorY": ay})
    # motion-frame consistency per (view, part)
    keys = sorted({(v, pid) for v, pid, _ in meas})
    for v, pid in keys:
        frames = sorted(f for vv, pp, f in meas if (vv, pp) == (v, pid))
        layer = meas[(v, pid, frames[0])][2]["layerId"]
        scope = f"{v}/{layer}/{pid}"
        ck.add("frames_complete", scope, "PASS" if frames == list(range(doc["frameCount"])) else "FAIL", detail={"frames": frames, "expected": doc["frameCount"]})
        if len(frames) > 1:
            zs = {meas[(v, pid, f)][2]["zOrder"] for f in frames}
            ck.add("zorder_stable_across_frames", scope, "PASS" if len(zs) == 1 else "NOT_RUN", detail=sorted(zs),
                   reason=None if len(zs) == 1 else "zOrder changes between frames; check the occlusion is intended")
            if layer == "L0_BASE_BODY":
                bottoms = [meas[(v, pid, f)][0]["contact"]["bottomRow"] for f in frames if meas[(v, pid, f)][0].get("bbox")]
                ck.add("body_ground_consistency", scope, "PASS" if bottoms and max(bottoms) - min(bottoms) <= max(2, round(H * 0.004)) else "FAIL", detail=bottoms)
                shas = [meas[(v, pid, f)][1] for f in frames]
                rep_at = [frames[i] for i in range(1, len(shas)) if shas[i] == shas[i - 1]]
                ck.add("body_frames_not_identical", scope, "PASS" if not rep_at else "FAIL", detail={"repeatedAt": rep_at})
    # compositing: reproducible, every layer can be toggled
    for v in doc["views"]:
        for f in range(doc["frameCount"]):
            scope = f"{v}/f{f:02d}"
            a, used = compose(doc, v, f, None, repo_root=repo_root)
            b, _ = compose(doc, v, f, None, repo_root=repo_root)
            ck.add("composite_reproducible", scope, "PASS" if a.tobytes() == b.tobytes() else "FAIL", detail={"order": used})
            for layer in LAYERS:
                off = [l for l in LAYERS if l != layer]
                c, used_off = compose(doc, v, f, off, repo_root=repo_root)
                present = any(p["layerId"] == layer and p["view"] == v and p["frameIndex"] == f for p in doc["parts"])
                if not present:
                    ck.add("layer_toggle", f"{scope}/{layer}", "NOT_RUN", reason="no part in this layer for this view/frame")
                    continue
                changed = c.tobytes() != a.tobytes()
                ck.add("layer_toggle", f"{scope}/{layer}", "PASS" if changed else "NOT_RUN", detail={"onWithout": used_off},
                       reason=None if changed else "turning the layer off changes nothing (fully hidden?); check by eye")
    for cid, label in design_protection_checks(doc["characterId"]):
        ck.add(cid, "design", "NOT_RUN", "human", reason="mandatory visual QA: " + label)
    ck.add("director_approval", "all", "NOT_RUN", "human", reason="layer parts are candidates until a director approval record exists")
    subj = {"kind": "modular-character", "characterId": doc["characterId"]}
    if doc_path:
        subj.update({"path": rel(doc_path, repo_root), "sha256": sha256_file(doc_path)})
    return make_report(subj, ck.rows)


# ---------- previews ----------
def comparison_sheet(images, labels, ground_y=None, pad=12):
    """Side-by-side sheet of same-size images (e.g. 4 views) with an optional shared ground line."""
    from PIL import Image, ImageDraw
    W, H = images[0].size
    sheet = Image.new("RGBA", (len(images) * (W + pad) + pad, H + 2 * pad + 28), (40, 44, 52, 255))
    d = ImageDraw.Draw(sheet)
    for i, (im, lab) in enumerate(zip(images, labels)):
        x = pad + i * (W + pad)
        sheet.alpha_composite(im.convert("RGBA"), (x, pad + 28))
        d.text((x + 4, pad), lab, fill=(255, 255, 255, 255))
    if ground_y is not None:
        d.line([0, pad + 28 + ground_y, sheet.width, pad + 28 + ground_y], fill=(240, 120, 60, 255), width=max(1, H // 400))
    return sheet


def previews(doc, out_dir, overwrite=False, repo_root=REPO_ROOT):
    """All-layer composites, each single-layer-OFF composite, and one 4-view sheet per frame."""
    out_dir = Path(out_dir)
    entries = []
    for f in range(doc["frameCount"]):
        row = []
        for v in doc["views"]:
            img, used = compose(doc, v, f, None, repo_root=repo_root)
            e = _save(img, out_dir / f"{v}_f{f:02d}_all.png", overwrite, repo_root)
            e.update({"kind": "composite", "view": v, "frame": f, "layers": LAYERS, "parts": used}); entries.append(e)
            row.append(img)
            for layer in LAYERS:
                off = [l for l in LAYERS if l != layer]
                img2, used2 = compose(doc, v, f, off, repo_root=repo_root)
                e = _save(img2, out_dir / f"{v}_f{f:02d}_without_{layer}.png", overwrite, repo_root)
                e.update({"kind": "composite", "view": v, "frame": f, "layers": off, "parts": used2}); entries.append(e)
        sheet = comparison_sheet(row, [f"{v} f{f:02d}" for v in doc["views"]], doc["anchor"]["px"][1])
        e = _save(sheet, out_dir / f"compare_4views_f{f:02d}.png", overwrite, repo_root)
        e.update({"kind": "comparison", "frame": f, "views": doc["views"]}); entries.append(e)
    record_outputs(out_dir, entries, repo_root)
    return entries


def compare_images(paths_by_label, out_path, ground_y=None, overwrite=False, repo_root=REPO_ROOT):
    from PIL import Image
    labels = list(paths_by_label)
    ims = []
    for lab in labels:
        with Image.open(Path(repo_root) / paths_by_label[lab]) as im:
            ims.append(im.convert("RGBA"))
    sheet = comparison_sheet(ims, labels, ground_y)
    e = _save(sheet, out_path, overwrite, repo_root)
    e.update({"kind": "comparison", "inputs": {k: {"path": v, "sha256": sha256_file(Path(repo_root) / v)} for k, v in paths_by_label.items()}})
    record_outputs(Path(out_path).parent, [e], repo_root)
    return e
