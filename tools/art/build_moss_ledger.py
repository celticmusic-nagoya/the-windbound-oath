"""Generate docs/art/moss_asset_ledger.md (+ .csv): one row per Moss Forest art PNG, with adoption / file delivery / GitHub / manifest / map placement / main / device verification kept as separate states."""
import csv, glob, json, re, subprocess
from pathlib import Path
import numpy as np
from PIL import Image
ROOT = Path(__file__).resolve().parents[2]
NEW = "fern_cluster_01 fern_cluster_02 fern_cluster_03 bush_forest_01 bush_forest_02 bush_forest_03 rock_moss_01 rock_moss_02 rock_moss_03 root_exposed_01 root_exposed_02 stump_rot_01 stump_rot_02 mushroom_cluster_01 mushroom_cluster_02 ruins_stone_01 ruins_stone_02 tree_ancient_great_01 tree_ancient_sentinel_01 tree_log_hollow_A3_01".split()
man = json.load(open(ROOT / 'img/field/moss/manifest.json')); rules = man['node'] + man['layer']
maps = {Path(f).name[:15]: open(f).read() for f in sorted(glob.glob(str(ROOT / 'data/maps/moss_forest_0*.json')))}
def category(i):
    for k, c in [('fern', 'vegetation'), ('bush', 'vegetation'), ('veg_', 'vegetation'), ('rock', 'rock'), ('root', 'root'), ('stump', 'stump'), ('mushroom', 'mushroom'), ('ruins', 'ruins'), ('anc_', 'ancient structure'), ('tree', 'tree'), ('prop_', 'prop'), ('fx_', 'fx'), ('a3_', 'A3 entity')]:
        if i.startswith(k): return c
    return 'other'
rows = []
files = sorted(Path(ROOT / 'img/field/moss/art').glob('*.png'))
for f in files:
    i = f.stem; im = Image.open(f); a = np.array(im.convert('RGBA'))[..., 3]
    edge = int(max(a[0].max(), a[-1].max(), a[:, 0].max(), a[:, -1].max()))
    rgba = im.mode == 'RGBA'; ok = rgba and a.min() == 0 and a[0, 0] == 0
    faint = round(100 * float(((a > 0) & (a <= 8)).mean()), 1)
    rule = next((r for r in rules if r.get('gen') == 'delivered_art' and re.search(r['match'], i) and Path(r['file']).stem == i), None)
    used = {m: len(re.findall(r'"%s"' % i, t)) for m, t in maps.items() if re.search(r'"%s"' % i, t)}
    new = i in NEW
    rows.append({'id': i, 'class': category(i), 'path': 'img/field/moss/art/%s.png' % i, 'size': '%dx%d' % im.size, 'mode': im.mode,
                 'alpha': ('OK' if ok else 'CHECK') + ' (edge alpha %d, faint a1-8 %.1f%%)' % (edge, faint),
                 'adopted': 'formally adopted (user, 2026-10-19 delivery)' if new else 'existing asset (prior adoption record not re-verified)',
                 'delivered_file': 'yes', 'github': 'branch assets/moss-additional-20261019 (not main)' if new else 'on main',
                 'manifest': 'NOT registered (by instruction)' if new else ('registered delivered_art %sx%s' % (rule['w'], rule['h']) if rule else 'no delivered_art rule'),
                 'map_use': ('referenced as node in ' + ','.join(used)) if used else 'not placed', 'main': 'not merged' if new else 'yes',
                 'device': 'UNVERIFIED', 'notes': ''})
for r in rows:
    if r['id'] in ('tree_ancient_great_01', 'tree_ancient_sentinel_01', 'tree_log_hollow_A3_01'):
        r['notes'] = 'A3 map already references this ID as a node (renders placeholder via rule ^tree_(log|ancient|dead) with no file); registering would change A3 rendering -> needs approval'
    if r['id'].startswith('rock_moss_0') and r['id'] in NEW:
        r['notes'] = 'manifest rule ^rock_ maps this ID to standin/rock_small.png; maps do not use rock_moss_01-03 (they use rock_moss_S/M/L)'
with open(ROOT / 'docs/art/moss_asset_ledger.csv', 'w', newline='') as fh:
    w = csv.DictWriter(fh, rows[0].keys()); w.writeheader(); w.writerows(rows)
h = ['id', 'class', 'path', 'size', 'mode', 'alpha', 'adopted', 'delivered_file', 'github', 'manifest', 'map_use', 'main', 'device', 'notes']
md = ['# Moss Forest art asset ledger', '', 'Generated by tools/art/build_moss_ledger.py. Adoption / file delivery / GitHub / manifest / map placement / main / device verification are separate states. **Device (Android/real device) = UNVERIFIED for all rows.**', '',
      '## A. Delivery 2026-10-19 (20 assets)', '', '| ' + ' | '.join(h) + ' |', '|' + '---|' * len(h)]
md += ['| ' + ' | '.join(r[k] for k in h) + ' |' for r in rows if r['id'] in NEW]
md += ['', '## B. Existing Moss Forest art (%d files)' % sum(1 for r in rows if r['id'] not in NEW), '', '| ' + ' | '.join(h) + ' |', '|' + '---|' * len(h)]
md += ['| ' + ' | '.join(r[k] for k in h) + ' |' for r in rows if r['id'] not in NEW]
open(ROOT / 'docs/art/moss_asset_ledger.md', 'w').write('\n'.join(md) + '\n')
print(len(rows), 'rows; new:', sum(1 for r in rows if r['id'] in NEW))
