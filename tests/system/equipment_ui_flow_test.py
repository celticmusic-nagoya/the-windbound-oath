# Acquire -> bag -> EQUIP tab -> stats. Training sword, Emma quest reward, cliff chest (stage-gated), UI click + keyboard. needs http.server 8765
import json, sys
from playwright.sync_api import sync_playwright
fails=[]; errs=[]
def check(c,m):
    print(('ok   ' if c else 'FAIL ')+m)
    if not c: fails.append(m)
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':1280,'height':720})
    pg.on('pageerror',lambda e:errs.append('PAGEERR '+str(e))); pg.on('console',lambda m:m.type=='error' and errs.append(m.text))
    pg.goto('http://localhost:8765/index.html'); pg.wait_for_timeout(1200)
    ev=lambda s: pg.evaluate(s)
    ev("PrologueProgress.seed(0);Quest.reset();FieldTalk.load(null);Inventory.reset();EquipmentManager.reset();MossForest.reset();localStorage.removeItem(SAVE_KEY)")
    base=ev("charStats('aidan')")
    # --- fresh-game initialization, then training (no grant here)
    ev("giveStarterSword()")
    ev("storyStage=1;startTraining()")
    check(ev("EquipmentManager.get('aidan').weapon")=='father_sword' and ev("Inventory.count('father_sword')")==0,'training start: Aidan retains the father sword from initialization')
    check(ev("charStats('aidan')")==base,'father sword changes no stats (Raider/boss balance protected)')
    ev("storyStage=1;startTraining()"); check(ev("EquipmentManager.get('aidan').weapon")=='father_sword' and ev("Inventory.count('father_sword')")==0,'a second training start gives nothing more')
    ev("$('#battle').style.display='none';storyStage=3")
    # --- Emma reward
    ev("Quest.accept('q_emma_charm');Inventory.add('charm_windward')")
    got=ev("Quest.report('q_emma_charm')")
    check(any(g['id']=='emma_charm' for g in got) and ev("Inventory.count('emma_charm')")==1,'Emma quest report grants the Emma charm into the bag')
    check(ev("charStats('aidan')")==base,'just owning it changes nothing until equipped')
    # --- cliff chest gate
    ev("closeDialogue();storyStage=3"); ev("document.querySelector('#hillExit').click()"); pg.wait_for_timeout(1500)
    t=[x for x in ev("MossForest.map.treasurePoints") if x['id']=='tr_c1_cairn'][0]
    def click_chest():
        pg.evaluate("([x,y])=>MossForest.teleportFeet(x-60,y+40)",[t['x'],t['y']]); pg.wait_for_timeout(800)
        pt=pg.evaluate("([x,y])=>{const r=document.querySelector('#forestWorld').getBoundingClientRect(),s=FieldCamera.scale;return [r.left+x*s,r.top+(y-14)*s]}",[t['x'],t['y']])
        pg.mouse.click(pt[0],pt[1]); pg.wait_for_timeout(600)
    ev("storyStage=3"); click_chest()
    check(ev("Inventory.count('ether')")==0 and 'tr_c1_cairn' not in ev("MossForest.opened"),'stage 3: the cairn chest stays shut (and unclaimed)')
    ev("storyStage=15"); click_chest()
    check(ev("Inventory.count('ether')")>=1 and ev("Inventory.count('iron_sword')")==0 and ev("Inventory.count('potion')")>=1,'stage 15: chest opens and gives the mana drop (魔力の雫) instead of the iron sword')
    # --- UI (the EQUIP tab opens only after the prologue)
    ev("document.querySelector('#menuOpen').click()")
    ev("EquipmentManager.reset();syncEquipTab()"); ev("renderSystemTab('equip')")
    check(ev("document.querySelector('[data-stab=equip]').hidden")==True and pg.locator('#systemBody [data-eq-slot]').count()==0,'before the unlock: the EQUIP tab is hidden and cannot be rendered')
    ev("grantStarterGear(true)"); ev("renderSystemTab('equip')")
    check(ev("document.querySelector('[data-stab=equip]').hidden")==False and ev("Inventory.count('leather_cap')")==1 and ev("Inventory.count('leather_armor')")==1 and ev("Inventory.count('bronze_ring')")==1,'unlock: tab shown and the fort starter gear is in the bag')
    ev("EquipmentManager.setStoryWeapon('aidan','father_sword')"); ev("renderSystemTab('equip')")
    check(pg.locator('#systemBody [data-eq-char]').count()>=1 and pg.locator('#systemBody [data-eq-slot]').count()==5,'EQUIP tab: character picker + 5 slots (weapon/head/body/accessory x2)')
    check('父の剣' in pg.inner_text('#systemBody'),'weapon slot shows the worn father sword')
    pg.click('[data-eq-slot="weapon"]'); check(pg.locator('[data-eq-on="iron_sword"]').count()==0,'the iron sword is not offered to Aidan')
    ev("EquipmentManager.setStoryWeapon('aidan','oath_sword')"); ev("renderSystemTab('equip')"); pg.click('[data-eq-slot="weapon"]')
    txt=pg.inner_text('#systemBody')
    check('誓いの剣' in txt and '固定' in txt and pg.locator('[data-eq-off="weapon"]').count()==0,'oath sword: shown as fixed, no unequip button, no candidates')
    pg.click('[data-eq-slot="head"]'); before=int(pg.inner_text('[data-stat="def"]'))
    pg.click('[data-eq-on="leather_cap"]'); after=int(pg.inner_text('[data-stat="def"]'))
    check(after==before+1 and ev("EquipmentManager.get('aidan').head")=='leather_cap','clicking 装備 on the cap: DEF %d -> %d'%(before,after))
    ev("Inventory.add('emma_charm')")
    pg.click('[data-eq-slot="accessory1"]'); txt=pg.inner_text('#systemBody')
    check('エマの護符' in txt and '銅の指輪' in txt and 'DEF' in txt,'accessory candidates show DEF/HP preview')
    pg.focus('[data-eq-slot="accessory1"]'); pg.keyboard.press('ArrowDown')
    check(pg.evaluate("document.activeElement.dataset.eqOn||document.activeElement.dataset.eqSlot||document.activeElement.dataset.eqOff||''")!='accessory1','ArrowDown moves focus to the next control')
    pg.focus('[data-eq-on="emma_charm"]'); pg.keyboard.press('Enter'); pg.wait_for_timeout(100)
    check(ev("EquipmentManager.get('aidan').accessory1")=='emma_charm','Enter on a candidate equips it into accessory slot 1')
    pg.click('[data-eq-slot="accessory2"]'); pg.click('[data-eq-on="bronze_ring"]')
    check(ev("EquipmentManager.get('aidan').accessory2")=='bronze_ring' and ev("charStats('aidan')")['def']==base['def']+1+2,'accessory slot 2 takes the second piece (DEF +1 cap, +2 charm)')
    check(pg.evaluate("document.activeElement&&document.activeElement.closest('#systemBody')!==null"),'focus stays inside the menu after re-render')
    pg.click('[data-eq-slot="accessory1"]'); pg.click('[data-eq-off="accessory1"]'); check(ev("!EquipmentManager.get('aidan').accessory1"),'外す empties the socket')
    pg.click('[data-eq-char="fiona"]'); txt=pg.inner_text('#systemBody')
    check('エイダン' not in pg.inner_text('.eqSlots'),'Fiona: her own sockets are shown')
    # --- phone viewport: no horizontal overflow
    pg.set_viewport_size({'width':390,'height':760}); pg.wait_for_timeout(200)
    ov=pg.evaluate("(()=>{const m=document.querySelector('#systemMenu');return m.scrollWidth-m.clientWidth})()")
    check(ov<=1,'390px wide: no horizontal overflow (%d)'%ov)
    pg.screenshot(path='/tmp/claude-0/equip_mobile.png')
    # --- save round-trip with worn gear
    pg.set_viewport_size({'width':1280,'height':720})
    ev("EquipmentManager.equip('aidan','emma_charm');renderSystemTab('save');saveGrowthData();EquipmentManager.reset();Inventory.reset();loadGrowthData()")
    check(ev("EquipmentManager.get('aidan').accessory1")=='emma_charm' and ev("EquipmentManager.isUnlocked()")==True,'save/load keeps worn gear and the unlock')
    check(not errs,'0 console errors %s'%errs[:3])
    b.close()
sys.exit(1 if fails else 0)
